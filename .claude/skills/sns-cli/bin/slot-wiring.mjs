#!/usr/bin/env node
/**
 * slot-wiring — the GENERATED slot wiring (ADR-065 decisions 5, 6 and 8; #1096).
 *
 *   node slot-wiring.mjs --emit  --deployment <dir> --csharp <dir> [--company <root namespace>]
 *   node slot-wiring.mjs --check --deployment <dir> --csharp <dir> [--company <root namespace>]
 *
 * WHY THIS IS GENERATED AND NOT WRITTEN. Slot wiring is mechanical, carries no business content,
 * and a mistake in it is silent *and* catastrophic — the right type in the wrong instance. That
 * combination is what this repository already generates rather than hand-writes (precedent: the
 * generated Manager use-case entry bodies, ADR-061). Before ADR-065 the spec composition wired the
 * store seams by hand, which is a place a human can wire the wrong thing and nothing goes red.
 *
 * WHAT IS EMITTED, from the one slot table:
 *
 *   1. per ResourceAccess, the SLOT CARRIER
 *      `Component/Access/<Stem>/Resource/<Access>Slots.cs` — one `required init` property per slot,
 *      named by the SLOT and typed by its seam. The Access takes this one object and reads
 *      `slots.InvoiceBlobs`; it never receives two same-typed parameters it could transpose, and
 *      the body names the slot rather than a position. `required` is what makes adding, removing or
 *      renaming a slot a compile error at every construction site rather than a silent rewiring.
 *      It lives in the `Resource` project because that project already holds the seam interfaces
 *      and is referenced by the Access's `Service` project, by every driver project, and by the
 *      spec composition — the three places that construct or consume a carrier.
 *
 *   2. the PRODUCTION composition `Composition/<System>ProductionSlots.cs` — one line per slot, all
 *      of the same shape: take this slot's settings by its configuration KEY, call the driver type's
 *      `Create`, hand the result to the carrier at this slot's name. It names a slot and a type,
 *      never a connection string (decision 7): no component reads configuration, and neither does
 *      this file — it is handed a settings source.
 *
 *   3. the SPEC composition `Spec/<Root>.Spec.Composition/<Root>SpecSlots.cs` — the same slot
 *      names, the same count and the same shape, with a simulator where the driver stands. The
 *      Access is handed its slots and never learns which world it is in.
 *
 *   4. the SETTINGS abstraction `iFX/Contract/IResourceSettings{,Source}.cs` — layer 3 of decision
 *      8, the only thing the generated composition knows about configuration. Generated for the
 *      same reason as the rest: it must be identical in every project, and an interface each
 *      project writes for itself is an interface that drifts.
 *
 *   5. the CREDENTIAL port `iFX/Contract/ISlotCredentials{,Source}.cs` — decision 8 as amended
 *      (#1727): a driver is handed its slot's credential port BESIDE its settings and asks it for
 *      the secret on EVERY call, so a rotated secret takes effect at once and no host restarts.
 *      Generated for the reason the settings abstraction is, and in the same place.
 *
 * THE ONE EXCEPTION, decided from the slot table alone (decision 8 as amended): the component that
 * PROVIDES credentials does not RECEIVE them. The slots under `utilities: - utility: SecretsUtility`
 * keep the one-argument factory, and that component's production factory takes settings alone.
 * That is what makes the composition acyclic by construction: the provider's slots are built from
 * settings, the provider over them, the credential source over the provider, and every other slot
 * from settings AND that source.
 *
 * THE TOPOLOGY IS HARD-CODED (decision 5). How many slots, each one's seam type, driver type and
 * name come from the model and never vary at runtime, so they are written into the generated text.
 * A mix-up there is a compile error rather than a runtime surprise.
 *
 * THE GENERATOR STAYS GENERIC (decision 8). It decides WHICH factory runs for WHICH slot and never
 * how a driver is built: it cannot know that a PostgreSQL driver needs a connection string while a
 * BusinessCentral driver needs a base URL, a tenant and client credentials, and it does not have to.
 * Each driver's own `static <Seam> Create(IResourceSettings, ISlotCredentials)` — or, for the
 * credential provider's own slots, `Create(IResourceSettings)` — knows that and validates its own
 * settings, and `[W3]` below holds every landed driver to its signature (#1097, #1727).
 *
 * OWNERSHIP MARKER — DELIBERATELY NOT THE SCAFFOLDER'S. Every file here carries a DO-NOT-EDIT
 * header naming its own source and the command that rewrites it, in the idiom of the generated
 * `<Seam>.schema.sql`. It is NOT the scaffolder's `<auto-generated> Generated by theagent2 from
 * <project>.method@<rev>` marker, and that is on purpose twice over: these files are generated from
 * the DEPLOYMENT VIEW and not from the model, so a model revision stamp would be a lie that
 * `provenance-check` would then enforce; and the scaffolder's orphan scan claims every marked `.cs`
 * under the tree it emits into, so wearing its marker would make each of these a reported orphan of
 * a generator that never produced them.
 *
 * Exit: 0 ok · 1 findings (`--check` only) · 2 usage or unreadable input.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname, resolve } from 'node:path';
import { readDeploymentView, layoutOf } from './deployment-view.mjs';
import { companyFlag, resolveRoot, specCompositionDir, specRootWouldShadow } from './project-root.mjs';

const TOOL = 'slot-wiring';
const rel = (p) => relative(process.cwd(), p) || p;
const die = (msg) => { console.error(`${TOOL}: ${msg}`); process.exit(2); };

const args = process.argv.slice(2);
const has = (name) => args.includes(name);
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 && i + 1 < args.length ? args[i + 1] : undefined;
};

const emit = has('--emit');
const check = has('--check');
if ([emit, check].filter(Boolean).length !== 1) die('exactly one of --emit or --check is required');
const deploymentDir = flag('--deployment');
const csharpDir = flag('--csharp');
if (!deploymentDir || !csharpDir) die('--deployment and --csharp are both required');
for (const p of [deploymentDir, csharpDir]) if (!existsSync(p)) die(`${rel(p)} does not exist`);

const view = readDeploymentView(deploymentDir, TOOL);
if (view.problems.length) {
  for (const p of view.problems) console.error(`${TOOL}: ${p}`);
  die('the deployment view does not hold — `deployment-view-check` is where these are reported');
}
// ADR-071 §1: the wiring is generated from RULED decisions. A factory for a product nobody ruled
// would make the guess real in code; the ruling is the Software Architect's, and it comes first.
if (view.unruled.length) {
  for (const u of view.unruled) console.error(`${TOOL}: UNRULED — ${u}`);
  die('the deployment view carries decisions still owed — nothing is wired for an unruled slot (ADR-071)');
}
if (!view.slots.length) die(`${rel(view.path)}: no slots — nothing to wire`);
const declaredSystem = String(view.system ?? '').trim();
if (!declaredSystem) die(`${rel(view.path)}: no 'system' — the generated namespaces are keyed to it`);

// ---------------------------------------------------------------- the C# root namespace
//
// Every namespace below is the one the SCAFFOLDER emitted, and the scaffolder builds it from the
// PROJECT name. `deployment-view.yaml`'s `system:` is a different field and routinely a different
// string — figaro's project is `Figaro` and its view opens `system: figaro`, which made this tool
// look for `csharp/Spec/figaro.Spec.Composition/figaroSpecSlots.cs` on a case-sensitive filesystem
// and report every landed file missing (figaro#372; the same defect #1343 fixed for
// `spec-seqcheck`). Resolution order and provenance line are #1343's, unchanged: `--company`, then
// the model store's `project.yaml`, then `system:` as a last resort. Case is never folded.
const { root, source: rootSource } = resolveRoot({
  company: companyFlag(args),
  searchDirs: [resolve(csharpDir, '..'), deploymentDir, resolve(deploymentDir, '..', '..', '..', '..')],
  fallback: declaredSystem,
  fallbackSource: "deployment-view.yaml 'system'",
});

// The spec composition project. `<Root>.Spec.Composition` is what this tool emits and what every
// landed tree carries; `<Root>.SpecLayer.Composition` is what a tree carries INSTEAD when the first
// would shadow the spec framework's own `TheAgent.Spec` — inside `namespace <Root>.SpecLayer.X`, a
// `Spec.For<T>(…)` binds `Spec` to the `<Root>.Spec` NAMESPACE and not to the framework's `Spec`
// class (measured downstream: 100+ CS0234 in one build). Whichever the tree has is the one written
// to. The generator resolves; it does not rename a project that already exists (figaro#372 part 2).
const composition = specCompositionDir(csharpDir, root);
const specNs = composition.name;

// …and the default name is NOT emitted silently into a tree it would break. `<Root>.Spec` shadows
// `TheAgent.Spec` for every authored spec under `<Root>.…`, and the failure is a hundred CS0234s at
// build time with nothing pointing back here. Where the shadow is real and the tree has not already
// taken the `<Root>.SpecLayer.Composition` way out, `--emit` refuses and names the way out; `--check`
// says it and carries on, because a project in that state is red at the compiler, not at this tool.
if (!composition.alternative) {
  const shadowed = specRootWouldShadow(csharpDir, root);
  if (shadowed.length) {
    const say = (m) => (emit ? die(`SHADOW — ${m}`) : console.error(`${TOOL}: SHADOW — ${m}`));
    say(`emitting \`${specNs}\` would declare a namespace \`${root}.Spec\`, and ${shadowed.length} spec ` +
      `source(s) under \`${root}.\` name \`Spec.\` by its simple name — e.g. ${rel(shadowed[0])}. In those ` +
      `files \`Spec.For<T>(…)\` would bind to the \`${root}.Spec\` NAMESPACE instead of the framework's ` +
      `\`TheAgent.Spec.Spec\` class, and every one of them would fail to compile (figaro#372 part 2). ` +
      `Name the project \`${root}.SpecLayer.Composition\` — create ` +
      `\`${rel(join(csharpDir, 'Spec', `${root}.SpecLayer.Composition`))}\` and re-run; this tool writes ` +
      `into it, and every checker resolves it, once it exists.`);
  }
}

// ---------------------------------------------------------------- naming

/** `sales-store` -> `SalesStore`. The slot name is the identity, so it is also the member name. */
const pascal = (name) =>
  String(name).split(/[-_\s]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('');

/**
 * `SalesAccess` -> `Sales`, `StorageUtility` -> `Storage`. The ADR-022 directory layout keys an
 * owner's projects on the stem under its tier directory — `Component/Access/Sales`,
 * `Component/Utility/Storage` — the same derivation `construction-entry-check` and `workspace
 * derive` make, read from the shared reader. A Utility that stands on a resource (ADR-071 §4)
 * gets the same carrier, the same composition lines and the same factories as an Access.
 */
const ownerOf = (o) => {
  const { tier, stem } = layoutOf(o.name, o.tier);
  return {
    name: o.name,
    tier,
    stem,
    carrier: `${o.name}Slots`,
    ns: `${root}.${tier}.${stem}.Resource`,
    path: join(csharpDir, 'Component', tier, stem, 'Resource', `${o.name}Slots.cs`),
    slots: o.slots,
  };
};
const owners = view.owners.filter((o) => o.slots.length).map(ownerOf);

/**
 * The driver assembly's namespace, from the slot's declared `driverProject` — the ADR-022 directory
 * convention read forwards: `Component/Access/Catalog/Store.Sqlite` is
 * `<System>.Access.Catalog.Store.Sqlite`. Derived from a DECLARED path, never from scanning the
 * tree for the driver: the slot table states where a driver lives for the same reason it states
 * which type it is (ADR-065 decision 8).
 */
const driverNs = (slot) =>
  `${root}.${String(slot.driverProject).replace(/^Component\//, '').split('/').join('.')}`;

/** The generated public factory of one slot, named by the SLOT, inside its driver project. */
const factoryOf = (slot) => ({
  slot,
  name: `${pascal(slot.slot)}Slot`,
  ns: driverNs(slot),
  dir: join(csharpDir, ...String(slot.driverProject).split('/')),
  path: join(csharpDir, ...String(slot.driverProject).split('/'), `${pascal(slot.slot)}Slot.cs`),
});
const factories = view.slots.map(factoryOf);

/**
 * The component that PROVIDES credentials does not RECEIVE them (ADR-065 decision 8 as amended,
 * #1727). Decided from the slot table alone and from no new key: the provider is the Utility
 * entered as `utilities: - utility: SecretsUtility`, and every slot under it keeps the one-argument
 * factory. Its slots are how the credential source is built, so handing them a credential port
 * would make the composition a cycle — the bootstrap (the platform identity the hosting grants
 * authenticates the credential store) is what lets them need none.
 */
const CREDENTIAL_PROVIDER = 'SecretsUtility';
const providesCredentials = (tier, name) => tier === 'Utility' && name === CREDENTIAL_PROVIDER;
/** True when this slot's driver is handed a credential port beside its settings. */
const receivesCredentials = (slot) => !providesCredentials(slot.ownerTier, slot.owner);

const productionPath = join(csharpDir, 'Composition', `${root}ProductionSlots.cs`);
const specPath = join(composition.dir, `${root}SpecSlots.cs`);
// One type per file: the repository's own Roslyn analyzer says so (IDESIGN021, DDC).
const settingsPath = join(csharpDir, 'iFX', 'Contract', 'IResourceSettings.cs');
const settingsSourcePath = join(csharpDir, 'iFX', 'Contract', 'IResourceSettingsSource.cs');
const credentialsPath = join(csharpDir, 'iFX', 'Contract', 'ISlotCredentials.cs');
const credentialsSourcePath = join(csharpDir, 'iFX', 'Contract', 'ISlotCredentialsSource.cs');
const retryPath = join(csharpDir, 'iFX', 'Contract', 'SlotRetry.cs');
const ifxNs = `${root}.iFX.Contract`;

/**
 * The DO-NOT-EDIT header. See the file header for why this is not the scaffolder's marker. The
 * source is named as a bare filename, the idiom the generated `<Seam>.schema.sql` already uses: a
 * path relative to the emitted file would differ per emitted file and say nothing extra.
 * `#nullable enable` is the second line for the same reason every generated C# file carries it.
 */
const header = (what) => [
  `// ${what} — GENERATED from the slot table in deployment-view.yaml by \`just slot-wiring\``,
  `// (ADR-065 decisions 5 and 8, #1096). DO NOT EDIT.`,
  `//`,
  `// To change what is wired, change the slot table and regenerate. \`just slot-wiring-check\``,
  `// fails while a committed file is not what the slot table emits today.`,
  '#nullable enable',
];

/** One reviewer-facing line per slot, identical wherever a slot is named. */
const slotNote = (s) =>
  `Slot '${s.slot}' of ${s.owner} — resource ${s.resource} (${s.resourceKind}${s.product ? ` / ${s.product}` : ''}).`;

// ---------------------------------------------------------------- the settings abstraction

/**
 * The slot's public way in (ADR-065 decision 6, #1098). The concrete driver is `internal`, so
 * nothing outside its own assembly can name it, let alone `new` it — the Access's `Service`
 * assembly cannot construct a store even by accident, and that guarantee is the LANGUAGE's rather
 * than a review's or an analyzer's. What is public is this one generated class, in the same
 * assembly, exposing the seam and nothing else.
 *
 * It is generated rather than written for the reason all the wiring is: it is mechanical, and a
 * hand-written one is a place where a slot could be pointed at the wrong driver with nothing going
 * red. What stays hand-written is what cannot be generated — the driver's own `Create`, which knows
 * what a PostgreSQL driver needs that a BusinessCentral driver does not (decision 8 layer 2).
 */
function factoryText(f) {
  const s = f.slot;
  const L = [...header(`${f.name}.cs`)];
  L.push('');
  L.push(`using ${ifxNs};`);
  L.push(`using ${owners.find((a) => a.name === s.owner).ns};`);
  L.push('');
  L.push(`namespace ${f.ns};`);
  L.push('');
  L.push('/// <summary>');
  L.push(`/// The one public way to build ${slotNote(s).replace(/\.$/, '')}.`);
  L.push('/// </summary>');
  L.push('/// <remarks>');
  L.push(`/// <c>${s.driverType}</c> is <c>internal</c> to this assembly (ADR-065 decision 6): the`);
  L.push('/// Access\'s <c>Service</c> assembly cannot name it, so it cannot construct a store — the');
  L.push('/// language enforces what a review otherwise has to. The generated production composition');
  L.push('/// calls this, hands it the slot\'s settings, and binds the result at this slot\'s name.');
  L.push('/// </remarks>');
  L.push(`public static class ${f.name}`);
  L.push('{');
  L.push(`    /// <summary>The slot's settings are resolved under the key <c>${s.configKey}</c>; the`);
  L.push('    /// driver binds and validates its own typed settings inside <c>Create</c>, so a missing');
  if (receivesCredentials(s)) {
    L.push('    /// value fails at startup naming the slot and the key. The credential port is this slot\'s');
    L.push('    /// own: the driver asks it for the secret on every call and holds nothing between calls');
    L.push('    /// (ADR-065 decision 8 as amended, #1727).</summary>');
    L.push(`    public static ${s.seam} Create(IResourceSettings settings, ISlotCredentials credentials)`);
    L.push(`        => ${s.driverType}.Create(settings, credentials);`);
  } else {
    L.push('    /// value fails at startup naming the slot and the key. This slot belongs to the component');
    L.push('    /// that PROVIDES credentials, so it is handed none: the platform identity the hosting');
    L.push('    /// grants is how it authenticates (ADR-065 decision 8 as amended, #1727).</summary>');
    L.push(`    public static ${s.seam} Create(IResourceSettings settings) => ${s.driverType}.Create(settings);`);
  }
  L.push('}');
  L.push('');
  return L.join('\n');
}

/**
 * `IResourceSettings` / `IResourceSettingsSource` — layer 3 of ADR-065 decision 8, the abstraction
 * the generated composition sees instead of the Configuration utility. Generated rather than
 * hand-authored per project for the reason the rest of this file is: it must be IDENTICAL in every
 * project, and an interface each project writes for itself is an interface that drifts. It goes in
 * the project's own iFX Contract because that is the layer both the composition and the drivers
 * already sit above, and it depends on nothing.
 */
function settingsText() {
  const L = [...header('IResourceSettings.cs')];
  L.push('');
  L.push(`namespace ${ifxNs};`);
  L.push('');
  L.push('/// <summary>');
  L.push('/// The settings of ONE slot, handed to that slot\'s driver at construction (ADR-065');
  L.push('/// decision 8). A driver binds its own typed settings class out of these and validates');
  L.push('/// them, so a missing or malformed value fails during <c>Create</c> — at application');
  L.push('/// startup, naming the slot and the key — rather than at the first call.');
  L.push('/// </summary>');
  L.push('/// <remarks>');
  L.push('/// No component ever sees this (decision 7): configuration is resolved at composition and');
  L.push('/// injected, the seam arrives already constructed and connected, and the Configuration');
  L.push('/// utility appears nowhere outside the composition root. The split is construction-time');
  L.push('/// versus runtime — cross-cutting services used DURING a call still go through the');
  L.push('/// Utilities bar from any layer, unchanged.');
  L.push('/// </remarks>');
  L.push('public interface IResourceSettings');
  L.push('{');
  L.push('    /// <summary>The slot these settings are for — what a validation message names.</summary>');
  L.push('    string Slot { get; }');
  L.push('');
  L.push('    /// <summary>One setting, or null when the source does not carry it.</summary>');
  L.push('    string? Value(string key);');
  L.push('');
  L.push('    /// <summary>');
  L.push('    /// One setting that the driver cannot start without. The message is the same in every');
  L.push('    /// project because it is written once, here: an operator reading a failed startup gets');
  L.push('    /// the slot and the key, which together say exactly which configuration entry to add.');
  L.push('    /// </summary>');
  L.push('    string Require(string key)');
  L.push('        => Value(key) is { Length: > 0 } value');
  L.push('            ? value');
  L.push('            : throw new InvalidOperationException(');
  L.push('                $"slot \'{Slot}\' has no setting \'{key}\' — its driver cannot be built. The slot table names "');
  L.push('                + "the configuration KEY each slot resolves under (deployment-view.yaml, `configKey`); the "');
  L.push('                + "VALUE belongs to this deployment\'s configuration and never to the design.");');
  L.push('}');
  L.push('');
  return L.join('\n');
}

/**
 * The bounded transient-retry policy of one slot (#1103). The slot table has always carried these
 * four numbers and, until this landed, NOTHING read them: every Access hard-coded the same values as
 * private consts, so the reviewed policy and the running policy were two statements of one fact with
 * nothing joining them. The ceiling is uniform per ADR-048 §2 and the backoff profile is per product,
 * which is exactly why it belongs to the slot rather than to the component.
 */
function retryText() {
  const L = [...header('SlotRetry.cs')];
  L.push('');
  L.push(`namespace ${ifxNs};`);
  L.push('');
  L.push('/// <summary>');
  L.push('/// One slot\'s bounded transient-retry policy, from the deployment view\'s slot table.');
  L.push('/// Retry lives in the ResourceAccess (ADR-048 §2) — the driver speaks the store\'s protocol');
  L.push('/// and nothing else — so the Access reads its policy off the slot it was handed rather than');
  L.push('/// restating the numbers a reviewer already blessed.');
  L.push('/// </summary>');
  L.push('/// <param name="MaxAttempts">Including the first: 3 is one attempt and two retries.</param>');
  L.push('/// <param name="Shape">The backoff profile, per product — e.g. exponential-jitter, fixed-short.</param>');
  L.push('/// <param name="BaseDelayMs">The first delay, in milliseconds.</param>');
  L.push('/// <param name="MaxDelayMs">The cap on any single delay, in milliseconds.</param>');
  L.push('public sealed record SlotRetry(int MaxAttempts, string Shape, double BaseDelayMs, double MaxDelayMs);');
  L.push('');
  return L.join('\n');
}

/** Layer 3's other half: the source the composition root supplies, once per application. */
function settingsSourceText() {
  const L = [...header('IResourceSettingsSource.cs')];
  L.push('');
  L.push(`namespace ${ifxNs};`);
  L.push('');
  L.push('/// <summary>');
  L.push('/// "Give me the settings for slot <c>catalog-store</c>" — supplied at the composition root,');
  L.push('/// once per application, over whatever this deployment configures with. It is the only thing');
  L.push('/// the generated production composition knows about configuration, and the Configuration');
  L.push('/// utility lives behind it and nowhere else (ADR-065 decision 7).');
  L.push('/// </summary>');
  L.push('public interface IResourceSettingsSource');
  L.push('{');
  L.push('    /// <summary>The settings of one slot, by its name in the slot table.</summary>');
  L.push('    IResourceSettings For(string slot);');
  L.push('}');
  L.push('');
  return L.join('\n');
}

/**
 * `ISlotCredentials` — the credential port of ONE slot (ADR-065 decision 8 as amended, #1727).
 * Generated beside `IResourceSettings` for the same reason: identical in every project. Three
 * verbs, each answering the string that goes on the wire; the driver asks on every call, so a
 * rotated secret takes effect at once. The port names no product and caches nothing.
 */
function credentialsText() {
  const L = [...header('ISlotCredentials.cs')];
  L.push('');
  L.push(`namespace ${ifxNs};`);
  L.push('');
  L.push('/// <summary>');
  L.push('/// The credentials of ONE slot, handed to that slot\'s driver at construction beside its');
  L.push('/// settings (ADR-065 decision 8 as amended, #1727). A driver asks on EVERY call and holds');
  L.push('/// nothing between calls, so a rotated secret takes effect on the very next call and no host');
  L.push('/// restarts. The settings carry the NAME a secret is filed under, never the secret.');
  L.push('/// </summary>');
  L.push('/// <remarks>');
  L.push('/// Every verb RAISES on failure rather than answering an envelope, so a driver never unwraps');
  L.push('/// one, and the raise happens on the driver\'s own stack, inside the calling Access\'s attempt.');
  L.push('/// The component that provides credentials is not handed this port: its own slots are built');
  L.push('/// from settings alone, which is what keeps the composition free of a cycle.');
  L.push('/// </remarks>');
  L.push('public interface ISlotCredentials');
  L.push('{');
  L.push('    /// <summary>The slot these credentials are for — what a fault message names.</summary>');
  L.push('    string Slot { get; }');
  L.push('');
  L.push('    /// <summary>The key filed under <paramref name="secretName"/>, unopened.');
  L.push('    /// <paramref name="headerName"/> is the driver\'s own knowledge of its product and');
  L.push('    /// travels with the ask.</summary>');
  L.push('    Task<string> ApiKey(string secretName, string headerName, CancellationToken ct);');
  L.push('');
  L.push('    /// <summary>The connection string filed under <paramref name="secretName"/>, unopened.</summary>');
  L.push('    Task<string> ConnectionString(string secretName, CancellationToken ct);');
  L.push('');
  L.push('    /// <summary>A live access token for the machine identity whose client registration is filed');
  L.push('    /// under <paramref name="secretName"/>. The mint, and any cache of it, belong to the');
  L.push('    /// component that provides credentials.</summary>');
  L.push('    Task<string> Bearer(string secretName, string tokenEndpoint, string? scope, CancellationToken ct);');
  L.push('}');
  L.push('');
  return L.join('\n');
}

/** The credential port's source, supplied once per application at the composition root. */
function credentialsSourceText() {
  const L = [...header('ISlotCredentialsSource.cs')];
  L.push('');
  L.push(`namespace ${ifxNs};`);
  L.push('');
  L.push('/// <summary>');
  L.push('/// "Give me the credential port for slot <c>catalog-store</c>" — the twin of');
  L.push('/// <see cref="IResourceSettingsSource"/>, supplied at the composition root over the component');
  L.push('/// that provides credentials, once per application (ADR-065 decision 8 as amended, #1727).');
  L.push('/// </summary>');
  L.push('public interface ISlotCredentialsSource');
  L.push('{');
  L.push('    /// <summary>The credential port of one slot, by its name in the slot table.</summary>');
  L.push('    ISlotCredentials For(string slot);');
  L.push('}');
  L.push('');
  return L.join('\n');
}

// ---------------------------------------------------------------- the carrier

function carrierText(a) {
  const L = [...header(`${a.carrier}.cs`)];
  L.push('');
  L.push(`using ${ifxNs};`);
  L.push('');
  L.push(`namespace ${a.ns};`);
  L.push('');
  L.push('/// <summary>');
  L.push(`/// The resource slots <c>${a.name}</c> stands on — one property per slot, NAMED BY THE SLOT`);
  L.push('/// (ADR-065 decision 2: the seam is a type and may repeat, so only the slot name tells two');
  L.push('/// slots apart). The Access is handed this one object and reads its slots by name, so it');
  L.push('/// never receives two same-typed parameters it could transpose, and it never learns whether');
  L.push('/// a real driver or a simulator is behind them (decision 5).');
  L.push('/// </summary>');
  L.push('/// <remarks>');
  L.push('/// Every property is <c>required</c>: adding, removing or renaming a slot is then a compile');
  L.push('/// error at every construction site rather than a silent rewiring.');
  L.push('/// </remarks>');
  L.push(`public sealed class ${a.carrier}`);
  L.push('{');
  a.slots.forEach((s, i) => {
    if (i) L.push('');
    L.push(`    /// <summary>${slotNote(s)}</summary>`);
    L.push(`    public required ${s.seam} ${pascal(s.slot)} { get; init; }`);
  });
  // The retry policy is TOPOLOGY, not instance state: it comes from the slot table, is the same in
  // both worlds, and never varies at runtime — so it belongs to the type rather than to an instance.
  // `retry` and its four numbers are required keys — the reader refuses a slot without them, so
  // there is nothing to default here and no silently-thin policy to emit.
  for (const s of a.slots) {
    const r = s.retry;
    L.push('');
    L.push(`    /// <summary>The bounded transient-retry policy of slot '${s.slot}' (ADR-048 §2: the`);
    L.push(`    /// ceiling is uniform, the backoff profile is per product).</summary>`);
    L.push(`    public static SlotRetry ${pascal(s.slot)}Retry { get; } = new(`);
    L.push(`        MaxAttempts: ${Number(r.maxAttempts)},`);
    L.push(`        Shape: "${String(r.shape)}",`);
    L.push(`        BaseDelayMs: ${Number(r.baseDelayMs)},`);
    L.push(`        MaxDelayMs: ${Number(r.maxDelayMs)});`);
  }
  L.push('}');
  L.push('');
  return L.join('\n');
}

