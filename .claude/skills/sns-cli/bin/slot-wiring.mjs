  L.push(`using ${ifxNs};`);
  for (const a of owners) L.push(`using ${a.ns};`);
  for (const ns of [...new Set(factories.map((f) => f.ns))].sort()) L.push(`using ${ns};`);
  L.push('');
  L.push(`namespace ${root}.Composition;`);
  L.push('');
  L.push('/// <summary>');
  L.push('/// The PRODUCTION half of the generated slot wiring (ADR-065 decision 5): every slot bound to');
  L.push('/// its real driver. Its spec twin is <c>' + root + 'SpecSlots</c> — same slot names, same');
  L.push('/// count, same shape, a simulator where the driver stands.');
  L.push('/// </summary>');
  L.push('/// <remarks>');
  L.push('/// <para>Each line does the same three things and nothing else: take this slot\'s settings by');
  L.push('/// its configuration KEY, call the driver type\'s <c>Create</c>, hand the result to the');
  L.push('/// carrier at this slot\'s name. It names a slot and a type and never a connection string —');
  L.push('/// no component reads configuration, and neither does this file (decision 7).</para>');
  L.push('/// <para>How a driver is built is the driver\'s own business: each exposes');
  L.push('/// <c>public static &lt;Seam&gt; Create(IResourceSettings, ISlotCredentials)</c>, binds its own');
  L.push('/// typed settings class and validates them, so a missing or malformed value fails at startup');
  L.push('/// naming the slot and the key (decision 8, #1097). It asks its credential port for the secret');
