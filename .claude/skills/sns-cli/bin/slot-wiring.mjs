/**
 * The orphan sweep. A carrier left behind when its Access loses its last slot, or is renamed, is a
 * file nothing regenerates and nothing deletes — and it still compiles, which is what makes it
 * dangerous rather than merely untidy. Scoped to the two shapes this tool writes.
 */
function orphans() {
  const found = [];
  for (const tierRoot of [join(csharpDir, 'Component', 'Access'), join(csharpDir, 'Component', 'Utility')]) {
    if (!existsSync(tierRoot)) continue;
    for (const stem of readdirSync(tierRoot)) {
      const dir = join(tierRoot, stem, 'Resource');
      if (!existsSync(dir) || !statSync(dir).isDirectory()) continue;
      for (const entry of readdirSync(dir))
        if (/Slots\.cs$/.test(entry) && !owned.has(join(dir, entry))) found.push(join(dir, entry));
    }
  }
  for (const dir of [join(csharpDir, 'Composition'), composition.dir])
    if (existsSync(dir))
      for (const entry of readdirSync(dir))
        if (/Slots\.cs$/.test(entry) && !owned.has(join(dir, entry))) found.push(join(dir, entry));
  // The generated per-slot factories, in whichever driver projects this run or a previous one used.
  for (const dir of new Set(factories.map((f) => f.dir)))
    if (existsSync(dir))
      for (const entry of readdirSync(dir))
        if (/Slot\.cs$/.test(entry) && !owned.has(join(dir, entry))) found.push(join(dir, entry));
  return found;
}

/**
 * Where each slot's driver type is declared, looked for in the project the slot table NAMES — never
 * by scanning the tree, for the same reason `driverType` is stated rather than resolved (ADR-065
 * decision 8).
 *
 * A slot whose driver is not there is NOT a failure: between Gate 3 and construction that is the
 * normal state of a project. A driver that IS there and does not expose the convention IS a
 * failure — that is #1097.
 */
function driverSites() {
  return view.slots.map((slot) => {
    const dir = join(csharpDir, ...String(slot.driverProject).split('/'));
    if (!existsSync(dir)) return { slot, file: null };
    const declaring = readdirSync(dir)
      .filter((e) => e.endsWith('.cs'))
      .map((e) => ({ path: join(dir, e), text: readFileSync(join(dir, e), 'utf-8') }))
      .find((f) => new RegExp(`\\b(class|record|struct)\\s+${slot.driverType}\\b`).test(f.text));
    return { slot, file: declaring ?? null, dir };
  });
}

/** The `.csproj` owning a source file: the nearest one at or above its directory, or null. */
function nearestProject(file) {
  let dir = dirname(file);
  for (let depth = 0; depth < 12; depth += 1) {
    if (!existsSync(dir)) return null;
    const found = readdirSync(dir).find((e) => e.endsWith('.csproj'));
    if (found) return join(dir, found);
    const up = dirname(dir);
    if (up === dir || !dir.startsWith(csharpDir)) return null;
    dir = up;
  }
  return null;
}

/**
 * [W3] — the driver convention of ADR-065 decision 8 (#1097, amended #1727): every driver type exposes
 *
 *     public static <Seam> Create(IResourceSettings settings, ISlotCredentials credentials)
 *
 * except a driver behind a slot of the component that PROVIDES credentials, which exposes
 *
 *     public static <Seam> Create(IResourceSettings settings)
 *
 * That signature is the whole seam between the generic half and the product half. The generator
 * cannot know that a PostgreSQL driver needs a connection string while a BusinessCentral driver
 * needs a base URL, a tenant and client credentials; it calls `Create` and each driver binds and
 * validates its own typed settings. Getting it wrong is a compile error in the generated
 * composition — but only once that composition is compiled, which is Step 7 or later, so this says
 * it at the moment the driver lands instead.
 *
 * The RETURN TYPE is the seam, not the driver: the composition hands the result straight to a
 * carrier property typed by the seam, and a driver that returns itself makes every consumer name a
 * concrete type the rest of the system must not know.
 */
function createConventionFindings(sites) {
  const found = [];
  for (const { slot, file } of sites) {
    if (!file) continue;
    // [W4] — the `driver:` package (#1103). The slot table names the package a driver is built on;
    // until this landed nothing read it, so a driver could be written against a different provider
    // than the one a Gate-3 reviewer blessed and no artifact would disagree.
    const project = nearestProject(file.path);
    if (project && !readFileSync(project, 'utf-8').includes(`Include="${slot.driver}"`))
      found.push(`${rel(project)}: [W4] declares ${slot.driverType} and references no \`${slot.driver}\` package — slot '${slot.slot}' of ${slot.owner} names that driver in the slot table, and a driver built on a different provider than the reviewed one is a Gate-3 decision quietly undone`);
    // [W5] — the driver is INVISIBLE outside its assembly (ADR-065 decision 6, #1098). A public
    // driver type can be named, and therefore constructed, by the Access's own `Service` assembly:
    // the one place in the system that must never build a store. `internal` is the language saying
    // so, which beats a review saying so and beats an analyzer checking it. Asked independently of
    // [W3]: a driver can perfectly well expose the right `Create` and still be visible to the
    // world, and that is the more dangerous of the two because everything looks right.
    if (new RegExp(`public\\s+(sealed\\s+|abstract\\s+|partial\\s+)*(class|record|struct)\\s+${slot.driverType}\\b`).test(file.text))
      found.push(`${rel(file.path)}: [W5] ${slot.driverType} is public — a driver is \`internal\` to its own assembly (ADR-065 decision 6), reachable only through the generated ${pascal(slot.slot)}Slot factory beside it. Public, the Access's own Service assembly can name it and construct a store`);

    // [W3] — the convention itself. `internal static` is as good as `public static`: the generated
    // factory beside the driver is in the same assembly and is what the composition calls. Which
    // of the two forms is owed is the slot table's answer (#1727): every slot takes the credential
    // port beside its settings except the slots of the component that PROVIDES credentials.
    const receives = receivesCredentials(slot);
    const oneArg = `IResourceSettings\\s+\\w+`;
    const twoArg = `IResourceSettings\\s+\\w+\\s*,\\s*ISlotCredentials\\s+\\w+`;
    const params = receives ? twoArg : oneArg;
    const createWith = (p, ret = slot.seam) =>
      new RegExp(`(?:public|internal)\\s+static\\s+(${ret})\\s+Create\\s*\\(\\s*${p}\\s*\\)`);
    if (createWith(params).test(file.text)) continue;
    const want = receives
      ? `static ${slot.seam} Create(IResourceSettings settings, ISlotCredentials credentials)`
      : `static ${slot.seam} Create(IResourceSettings settings)`;
    const wrongReturn = createWith(params, '\\w+').exec(file.text);
    const otherForm = createWith(receives ? oneArg : twoArg, '\\w+').test(file.text);
    found.push(wrongReturn
      ? `${rel(file.path)}: [W3] ${slot.driverType}.Create returns ${wrongReturn[1]}, and slot '${slot.slot}' is reached through ${slot.seam} — the composition hands the result to a carrier property typed by the SEAM, and a driver that returns itself makes every consumer name a type the rest of the system must not know`
      : `${rel(file.path)}: [W3] ${slot.driverType} declares no \`${want}\` — slot '${slot.slot}' of ${slot.owner} cannot be built by the generated composition (ADR-065 decision 8). ` +
        (receives
          ? (otherForm ? 'It still declares the one-argument form: since #1727 the generated factory hands every driver its slot\'s credential port beside its settings, and the driver asks it for the secret on every call. ' : '')
          : (otherForm ? `It declares the two-argument form, and ${CREDENTIAL_PROVIDER} is the component that PROVIDES credentials — its slots are handed none, which is what keeps the composition free of a cycle (#1727). ` : '')) +
        'Inside it the driver binds and validates its own typed settings, so a missing value fails at startup naming the slot and the key');
  }
  return found;
}

