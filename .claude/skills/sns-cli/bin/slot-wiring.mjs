/** `new XSlots { A = …, B = … }`, written across lines with one slot per line and a note above it. */
function carrierLiteral(a, valueOf, indent) {
  const pad = ' '.repeat(indent);
  const L = [`${pad}new ${a.carrier}`, `${pad}{`];
  for (const s of a.slots) {
    L.push(`${pad}    // ${slotNote(s)}`);
    L.push(`${pad}    ${pascal(s.slot)} = ${valueOf(s)},`);
  }
  L.push(`${pad}}`);
  return L;
}

