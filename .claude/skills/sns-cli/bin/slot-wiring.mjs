  L.push('/// were a place a human could wire the wrong instance with nothing going red. Each simulator');
  L.push('/// is registered TWICE and deliberately: with the spec, which applies the case\'s seeds and');
  L.push('/// armed faults and reads the attempt and effect observations back, naming the SLOT so a');
  L.push('/// gate violation names the instance and not just the interface (#1101); and with the');
